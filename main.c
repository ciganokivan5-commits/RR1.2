/**
 * @file array_odd_product.c
 * @brief Обчислення добутку непарних значень у статичному масиві цілих чисел.
 *
 * Умова: Реалізувати окрему функцію, яка отримує масив та його розмір,
 * підраховує добуток непарних значень та повертає знайдене значення[cite: 5].
 */

#include <stdio.h>
#include <windows.h> // Необхідно для керування кодуванням консолі Windows

/**
 * @brief Обчислює добуток непарних значень елементів масиву.
 *
 * @param arr Вхідний масив цілих чисел.
 * @param size Кількість елементів у масиві.
 * @return long long Добуток непарних значень (використовується long long для уникнення переповнення).
 */
long long calculateOddValuesProduct(const int arr[], int size) {
    // Змінна для накопичення добутку.
    // Ініціалізується одиницею (нейтральний елемент для множення).
    long long product = 1;

    // Прапорець для перевірки, чи були знайдені непарні елементи у масиві
    int found_odd = 0;

    // Поелементний обхід масиву
    for (int i = 0; i < size; i++) {
        // Перевірка на непарність значення елемента за допомогою оператора залишку від ділення
        if (arr[i] % 2 != 0) {
            product *= arr[i]; // Накопичення добутку непарних значень
            found_odd = 1;     // Фіксуємо факт знаходження хоча б одного непарного числа
        }
    }

    // Якщо в масиві не було знайдено жодного непарного значення, логічно повернути 0
    if (!found_odd) {
        return 0;
    }

    return product;
}

/**
 * @brief Головна точка входу в програму.
 * @return int Код завершення виконання програми (0 - успішно).
 */
int main(void) {
    // Встановлення кодування UTF-8 для коректного виведення в консоль
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Оголошення та стаτική ініціалізація масиву цілих чисел
    int static_array[] = {10, 230, 330, 100, 72, 67};

    // Обчислення реальної кількості елементів у статичному масиві
    int array_size = sizeof(static_array) / sizeof(static_array[0]);

    // Виведення початкового масиву на екран
    printf("--- Array Analysis Program ---\n");
    printf("Array elements: ");
    for (int i = 0; i < array_size; i++) {
        printf("%d ", static_array[i]);
    }
    printf("\n");

    // Виклик розробленої функції для підрахунку добутку непарних значень
    long long odd_product = calculateOddValuesProduct(static_array, array_size);

    // Виведення результату роботи програми
    printf("Product of odd values in the array: %lld\n", odd_product);

    return 0; // Успішне завершення програми
}
